# Makes every size and format of the project logo from the templates in
# assets/logo (UI-023): the favicon, the app icon with the web manifest and
# the logos of the interface. The output is plain text and depends on the
# templates alone, so it is the same on every machine. Vector only: no
# rasterizer is part of the toolchain, and every supported browser takes an
# SVG favicon and SVG manifest icons.
#
#   scripts/logo.sh                 writes the files into the work tree
#   scripts/logo.sh --check [ROOT]  fails if the files under ROOT (default:
#                                   the work tree) differ from the templates
set -eu
cd "$(dirname "$0")/.."
src=assets/logo
# The dark background of the interface (--background in web/src/index.css):
# the app icon fills its square with it, so the mark keeps its contrast on
# any launcher.
background='#0b0d12'
marker='<!-- Code generated by scripts/logo.sh from assets/logo; DO NOT EDIT. -->'
# Generated files, relative to the repository root.
files='web/public/favicon.svg web/public/icon.svg web/public/manifest.json web/src/assets/logo/logo.svg web/src/assets/logo/logo-dark.svg web/src/assets/logo/mark.svg'

die() { echo "logo.sh: $*" >&2; exit 1; }

# template checks the form the transformations below rely on: the SPDX
# comment first, then the svg element on a line of its own, closed on the
# last line.
template() {
  [ -f "$src/$1" ] || die "missing template $src/$1"
  head -n 1 "$src/$1" | grep -q '^<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->$' || die "$src/$1: first line is not the SPDX comment"
  sed -n 2p "$src/$1" | grep -q '^<svg ' || die "$src/$1: second line does not open the svg element"
  tail -n 1 "$src/$1" | grep -q '^</svg>$' || die "$src/$1: last line does not close the svg element"
}

# copy writes a template with the generated marker below its SPDX line.
copy() { # template, target
  template "$1"
  awk -v m="$marker" 'NR == 1 { print; print m; next } { print }' "$src/$1" >"$2"
}

# icon puts the mark on the dark square, scaled into the safe zone of a
# maskable icon (a circle of 80 % of the side): the mark spans 40 x 48 of
# its 64 x 64 box around (32, 33); at 0.75 its corners stay within 24 of
# the centre.
icon() { # target
  template rconductor-mark.svg
  {
    head -n 1 "$src/rconductor-mark.svg"
    echo "$marker"
    echo '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="RCONductor">'
    echo "  <rect width=\"64\" height=\"64\" fill=\"$background\"/>"
    echo '  <g transform="translate(8 7.25) scale(0.75)">'
    sed -e '1,2d' -e '$d' "$src/rconductor-mark.svg" | sed 's/^/  /'
    echo '  </g>'
    echo '</svg>'
  } >"$1"
}

manifest() { # target
  cat >"$1" <<EOF
{
  "name": "ShadowGhost.NET RCONductor",
  "short_name": "RCONductor",
  "start_url": ".",
  "scope": ".",
  "display": "standalone",
  "background_color": "$background",
  "theme_color": "$background",
  "icons": [
    { "src": "favicon.svg", "sizes": "any", "type": "image/svg+xml", "purpose": "any" },
    { "src": "icon.svg", "sizes": "any", "type": "image/svg+xml", "purpose": "maskable" }
  ]
}
EOF
}

generate() { # root
  mkdir -p "$1/web/public" "$1/web/src/assets/logo"
  copy rconductor-mark.svg "$1/web/public/favicon.svg"
  icon "$1/web/public/icon.svg"
  manifest "$1/web/public/manifest.json"
  copy rconductor-logo.svg "$1/web/src/assets/logo/logo.svg"
  copy rconductor-logo-dark.svg "$1/web/src/assets/logo/logo-dark.svg"
  copy rconductor-mark.svg "$1/web/src/assets/logo/mark.svg"
}

case "${1:-}" in
  "")
    [ $# -eq 0 ] || die "usage: logo.sh [--check [ROOT]]"
    generate .
    ;;
  --check)
    [ $# -le 2 ] || die "usage: logo.sh [--check [ROOT]]"
    root=${2:-.}
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' EXIT
    generate "$tmp"
    stale=
    for f in $files; do
      cmp -s "$tmp/$f" "$root/$f" || stale="$stale $f"
    done
    [ -z "$stale" ] || die "not made from $src, run scripts/logo.sh:$stale"
    ;;
  *) die "usage: logo.sh [--check [ROOT]]" ;;
esac
